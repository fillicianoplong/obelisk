import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outPath = path.join(root, 'src/renderer/editor/format/csp-format.css');

const ALIGNMENTS = ['left', 'center', 'right', 'justify'];
const LINE_SPACINGS = ['single', '1.15', '1.5', 'double'];
const SPACE_BEFORE_AFTER_PT = [0, 6, 12, 18, 24];
const INDENT_STEP_IN = 0.25;
const INDENT_LEFT_MIN_IN = 0;
const INDENT_LEFT_MAX_IN = 3;
const INDENT_FIRST_MAX_IN = 1;
const INDENT_HANGING_MAX_IN = 1;
const FONT_SIZES_PT = [8, 9, 10, 11, 12, 14, 16, 18, 20, 24, 28, 36, 48, 72];

const BUNDLED_FONT_FAMILIES = [
  'Liberation Serif',
  'Liberation Sans',
  'Liberation Mono',
  'Caladea',
  'Carlito',
  'DejaVu Serif',
  'DejaVu Sans',
  'DejaVu Sans Mono',
  'Linux Libertine G',
  'Linux Biolinum G',
  'Noto Serif',
  'Noto Sans',
  'Dancing Script',
];

function indentSteps(min, max) {
  const values = [];
  for (let value = min; value <= max + 1e-9; value += INDENT_STEP_IN) {
    values.push(Math.round(value * 100) / 100);
  }
  return values;
}

function cssQuote(value) {
  return `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function indentKey(value) {
  return String(value);
}

const lines = [
  '/* Generated by scripts/generate-editor-format-css.mjs. Do not edit by hand. */',
  '',
  '.page-sheet p {',
  '  line-height: 1;',
  '  margin-block: 0;',
  '  text-align: left;',
  '}',
  '',
];

for (const align of ALIGNMENTS) {
  if (align === 'left') {
    continue;
  }
  lines.push(`.page-sheet p[data-align=${cssQuote(align)}] { text-align: ${align}; }`);
}
lines.push('');

for (const spacing of LINE_SPACINGS) {
  const height = spacing === 'single' ? '1' : spacing === 'double' ? '2' : spacing;
  lines.push(`.page-sheet p[data-line-spacing=${cssQuote(spacing)}] { line-height: ${height}; }`);
}
lines.push('');

for (const pt of SPACE_BEFORE_AFTER_PT) {
  if (pt === 0) {
    continue;
  }
  lines.push(`.page-sheet p[data-space-before="${pt}"] { margin-block-start: ${pt}pt; }`);
}
for (const pt of SPACE_BEFORE_AFTER_PT) {
  if (pt === 0) {
    continue;
  }
  lines.push(`.page-sheet p[data-space-after="${pt}"] { margin-block-end: ${pt}pt; }`);
}
lines.push('');

const leftValues = indentSteps(INDENT_LEFT_MIN_IN, INDENT_LEFT_MAX_IN);
const firstValues = indentSteps(INDENT_STEP_IN, INDENT_FIRST_MAX_IN);
const hangingValues = indentSteps(INDENT_STEP_IN, INDENT_HANGING_MAX_IN);

for (const left of leftValues) {
  if (left === 0) {
    continue;
  }
  lines.push(
    `.page-sheet p[data-indent-left="${indentKey(left)}"][data-indent-first="0"][data-indent-hanging="0"] { padding-inline-start: ${left}in; }`,
  );
}

for (const first of firstValues) {
  for (const left of leftValues) {
    const selector = `.page-sheet p[data-indent-left="${indentKey(left)}"][data-indent-first="${indentKey(first)}"][data-indent-hanging="0"]`;
    if (left > 0) {
      lines.push(`${selector} { padding-inline-start: ${left}in; text-indent: ${first}in; }`);
    } else {
      lines.push(`${selector} { text-indent: ${first}in; }`);
    }
  }
}

for (const hanging of hangingValues) {
  for (const left of leftValues) {
    const total = left + hanging;
    lines.push(
      `.page-sheet p[data-indent-left="${indentKey(left)}"][data-indent-first="0"][data-indent-hanging="${indentKey(hanging)}"] { padding-inline-start: ${total}in; text-indent: -${hanging}in; }`,
    );
  }
}
lines.push('');

lines.push('.page-sheet span[data-underline="true"] { text-decoration: underline; }');
lines.push('');

for (const pt of FONT_SIZES_PT) {
  lines.push(`.page-sheet span[data-font-size="${pt}"] { font-size: ${pt}pt; }`);
}
lines.push('');

for (const family of BUNDLED_FONT_FAMILIES) {
  lines.push(`.page-sheet span[data-font-family=${cssQuote(family)}] { font-family: ${family}; }`);
}
lines.push('');

writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8');
console.log(`Wrote ${path.relative(root, outPath)}`);
