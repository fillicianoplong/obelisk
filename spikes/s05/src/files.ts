import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import type { SaveCase } from './cases';

export interface FileSnap {
  path: string;
  exists: boolean;
  size: number | null;
  mtimeMs: number | null;
  sha256: string | null;
}

export function snap(filePath: string): FileSnap {
  if (!fs.existsSync(filePath)) {
    return { path: filePath, exists: false, size: null, mtimeMs: null, sha256: null };
  }
  const stat = fs.statSync(filePath);
  if (!stat.isFile()) {
    return { path: filePath, exists: true, size: stat.size, mtimeMs: stat.mtimeMs, sha256: null };
  }
  const sha256 = crypto.createHash('sha256').update(fs.readFileSync(filePath)).digest('hex');
  return { path: filePath, exists: true, size: stat.size, mtimeMs: stat.mtimeMs, sha256 };
}

export function directorySnap(dir: string): Record<string, FileSnap> {
  const out: Record<string, FileSnap> = {};
  for (const name of fs.readdirSync(dir).sort()) {
    out[name] = snap(path.join(dir, name));
  }
  return out;
}

export function changedNames(before: Record<string, FileSnap>, after: Record<string, FileSnap>): string[] {
  const names = [...new Set([...Object.keys(before), ...Object.keys(after)])].sort();
  return names.filter((name) => {
    const left = before[name];
    const right = after[name];
    if (!left || !right) return true;
    return left.exists !== right.exists || left.size !== right.size || left.sha256 !== right.sha256;
  });
}

export function writeFixtures(dir: string, cases: readonly SaveCase[]): void {
  fs.mkdirSync(dir, { recursive: true });
  for (const item of cases) {
    const body = `S-05 fixture\n${item.fileName}\nDo not edit this file. The spike compares these bytes after the dialog closes.\n`;
    fs.writeFileSync(path.join(dir, item.fileName), body, 'utf8');
  }
}

export function fixtureBodyChanged(before: FileSnap, after: FileSnap): boolean {
  return before.exists !== after.exists || before.size !== after.size || before.sha256 !== after.sha256;
}

/** Prove the hash comparison can see a one-byte edit and a restore. */
export function selfTest(dir: string): { pass: boolean; detail: string } {
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, 'self-test.txt');
  try {
    fs.writeFileSync(file, 'alpha\n');
    const first = snap(file);
    fs.writeFileSync(file, 'alpha!\n');
    const edited = snap(file);
    fs.writeFileSync(file, 'alpha\n');
    const restored = snap(file);
    const pass = first.sha256 !== null && first.sha256 !== edited.sha256 && first.sha256 === restored.sha256;
    return {
      pass,
      detail: pass
        ? `A one-byte edit changed the sha256, and restoring the bytes brought it back (${first.sha256}).`
        : `Hash check failed. before=${first.sha256} edited=${edited.sha256} restored=${restored.sha256}`,
    };
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}
